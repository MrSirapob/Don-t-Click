let best = Number(localStorage.getItem(CONFIG.bestKey) || 0);
let lossCount = 0;
ui.best.textContent = best;

function randomTaunt(round) {
  const pool = DEATH_TAUNTS[round] || [];
  if (!pool.length) return "โอเค รอบนี้เกมยอมรับว่าคุณแพ้";
  return pool[Math.floor(Math.random() * pool.length)];
}

const engine = new GameEngine({
  rounds: ROUNDS,
  ui,
  scorePerRound: CONFIG.scorePerRound,
  onEnd: (won, round, score, reason) => {
    ui.screen.classList.add("hidden");
    ui.result.classList.remove("hidden");
    ui.finalRound.textContent = round;
    ui.finalScore.textContent = score;

    if (ui.resultMark) {
      ui.resultMark.textContent = won ? "✓" : "!";
    }
    if (won) {
      ui.resultTitle.textContent = "โอเค คุณชนะ";
      ui.resultMessage.textContent = "เกมพยายามกวนคุณตั้ง 20 รอบ แต่คุณยังไม่ยอมแพ้";
      ui.result.classList.add("result-win");
      ui.result.classList.remove("result-loss");
    } else {
      lossCount++;
      ui.resultTitle.textContent = randomTaunt(round);
      ui.resultMessage.textContent = `สาเหตุ: ${reason}`;
      ui.result.classList.add("result-loss");
      ui.result.classList.remove("result-win");
    }

    if (score > best) {
      best = score;
      localStorage.setItem(CONFIG.bestKey, String(best));
      ui.best.textContent = best;
    }
  }
});

function start() {
  ui.result.classList.add("hidden");
  ui.screen.classList.remove("hidden");
  ui.result.classList.remove("result-win", "result-loss");
  engine.start();
}

// Render gameplay exactly once per round.
const originalShowRound = engine.showRound.bind(engine);
engine.showRound = () => {
  const result = originalShowRound();
  if (ui.progress) {
    ui.progress.style.width = `${((engine.roundIndex + 1) / ROUNDS.length) * 100}%`;
  }
  ui.arena.classList.remove("round-enter");
  void ui.arena.offsetWidth;
  ui.arena.classList.add("round-enter");
  playRound(engine, ui);
  return result;
};

ui.restart.addEventListener("click", start);
start();
